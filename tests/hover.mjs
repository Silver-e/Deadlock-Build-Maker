import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5173');
await page.getByRole('navigation',{name:'Planner pages'}).getByRole('button',{name:'Spirit',exact:true}).click();
const card=page.locator('#shop .item').filter({has:page.getByRole('button',{name:'Inspect Cold Front',exact:true})}).locator('.item-main');
await card.hover();
let tip=page.getByRole('tooltip');await tip.waitFor();
assert.match(await tip.innerText(),/Cold Front/);assert.match(await tip.innerText(),/\+6%\s+Spirit Resist/);assert.match(await tip.innerText(),/Release an expanding ice blast/);assert.match(await tip.innerText(),/95\s*x0.47\s*Damage/);assert.match(await tip.innerText(),/25s cooldown/);
assert.match(await card.getAttribute('aria-label'),/^Add to/,'Hover must not add the item');
await tip.hover();await page.getByRole('tooltip').waitFor();
await page.screenshot({path:'test-results/hover.png',fullPage:false,animations:'disabled'});
const bounds=await tip.boundingBox();assert.ok(bounds.x>=0&&bounds.y>=0&&bounds.x+bounds.width<=1440&&bounds.y+bounds.height<=1000,'Tooltip stays in viewport');
await page.keyboard.press('Escape');await tip.waitFor({state:'hidden'});
await card.hover();await page.getByRole('tooltip').waitFor();await card.click();
await page.getByRole('button',{name:'Remove from Early Game: Cold Front',exact:true}).waitFor();
await page.getByRole('tooltip').waitFor({state:'hidden'});
await page.mouse.move(0,0);
await page.keyboard.press('Tab');await card.focus();
await page.getByRole('tooltip').waitFor();
assert.equal(await card.getAttribute('aria-describedby'),await page.getByRole('tooltip').getAttribute('id'));
await page.keyboard.press('Escape');
await page.getByRole('button',{name:'Inspect Cold Front',exact:true}).click();
await page.locator('.item-detail').waitFor();assert.equal(await page.getByRole('tooltip').count(),0);
await page.keyboard.press('Escape');
await page.setViewportSize({width:390,height:844});
await page.getByRole('button',{name:'Add to Early Game: Mystic Burst',exact:true}).hover();
tip=page.getByRole('tooltip');await tip.waitFor();
const small=await tip.boundingBox();assert.ok(small.x>=0&&small.x+small.width<=390&&small.y>=0&&small.y+small.height<=844);
await page.screenshot({path:'test-results/hover-small.png',fullPage:false,animations:'disabled'});
assert.deepEqual(errors,[]);
const touch=await browser.newContext({viewport:{width:390,height:844},hasTouch:true,isMobile:true});
const mobile=await touch.newPage();await mobile.goto('http://127.0.0.1:5173');await mobile.getByRole('navigation',{name:'Planner pages'}).getByRole('button',{name:'Weapon',exact:true}).tap();
await mobile.getByRole('button',{name:'Add to Early Game: Extended Magazine',exact:true}).tap();
assert.equal(await mobile.getByRole('tooltip').count(),0);
console.log('Hover passed: stats/descriptions/effects, no accidental addition, hoverable content, Escape, keyboard association, pinned details, viewport clamping and touch.');
await browser.close();
